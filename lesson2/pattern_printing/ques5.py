N = 4

# Bahar wala loop (Rows ke liye)
for i in range(N):  # i ki value hogi: 0, 1, 2, 3
    
    # Andar wala loop (Columns ke liye)
    for j in range(N):  # j ki value bhi hogi: 0, 1, 2, 3
        print("*", end=" ")  # Star print karo aur space dedo (next line me mat jao)
        
    print()  # Jab andar wala loop khatam ho jaye, to line change karo (Enter maro)

